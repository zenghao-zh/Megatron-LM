#!/bin/bash
# =============================================================================
# Lesson 03: nsys CLI 分析脚本
#
# 从 .nsys-rep 文件中提取关键性能指标，无需 GUI。
#
# 用法:
#   bash analyze_nsys_report.sh <path/to/file.nsys-rep>
#
# 示例:
#   bash tutorials/nsight_profiling/03_nsys_cli_analysis/analyze_nsys_report.sh \
#        nsys_profiles/smollm-360m-nsys-demo_0.nsys-rep
# =============================================================================

set -e

if [ $# -lt 1 ]; then
    echo "用法: $0 <nsys-rep-file>"
    echo "示例: $0 nsys_profiles/smollm-360m-nsys-demo_0.nsys-rep"
    exit 1
fi

REPORT=$1

if [ ! -f "$REPORT" ]; then
    echo "错误: 文件不存在: $REPORT"
    exit 1
fi

echo ""
echo "================================================================"
echo "  Nsight Systems CLI 分析"
echo "  报告文件: $REPORT"
echo "================================================================"

# ------------------------------------------------------------------
# 1. CUDA GPU Kernel 汇总 -- 找出最耗时的 kernel
# ------------------------------------------------------------------
echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  1. Top CUDA Kernels (按 GPU 时间排序)                      ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
nsys stats --report cuda_gpu_kern_sum "$REPORT" 2>/dev/null || \
    echo "[跳过] 无法生成 kernel 统计"

# ------------------------------------------------------------------
# 2. CUDA API 调用汇总 -- 看 CPU 端调用开销
# ------------------------------------------------------------------
echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  2. CUDA API 调用汇总 (CPU 端)                              ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
nsys stats --report cuda_api_sum "$REPORT" 2>/dev/null || \
    echo "[跳过] 无法生成 CUDA API 统计"

# ------------------------------------------------------------------
# 3. NVTX Range 汇总 -- 看 Megatron 标注的逻辑区域耗时
# ------------------------------------------------------------------
echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  3. NVTX Range 汇总 (Megatron 标注的逻辑区域)               ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
nsys stats --report nvtx_sum "$REPORT" 2>/dev/null || \
    echo "[跳过] 无法生成 NVTX 统计"

# ------------------------------------------------------------------
# 4. GPU 内存操作汇总
# ------------------------------------------------------------------
echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  4. GPU 内存操作汇总                                        ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
nsys stats --report gpu_mem_size_sum "$REPORT" 2>/dev/null || \
    echo "[跳过] 无法生成内存统计 (需要 --cuda-memory-usage true)"

# ------------------------------------------------------------------
# 5. 导出 SQLite 供高级分析
# ------------------------------------------------------------------
SQLITE_FILE="${REPORT%.nsys-rep}.sqlite"
echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  5. 导出 SQLite 数据库                                      ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
if [ ! -f "$SQLITE_FILE" ]; then
    nsys export --type sqlite --output "$SQLITE_FILE" "$REPORT" 2>/dev/null && \
        echo "已导出: $SQLITE_FILE" || \
        echo "[跳过] 导出失败"
else
    echo "已存在: $SQLITE_FILE"
fi

echo ""
echo "================================================================"
echo "  分析完成"
echo ""
echo "  进阶用法:"
echo "    - 用 sqlite3 $SQLITE_FILE 进行自定义查询"
echo "    - 用 Python + sqlite3 模块进行编程分析"
echo "    - 详见 README.md 中的 SQLite 查询示例"
echo "================================================================"
